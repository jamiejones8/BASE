const assert=require('node:assert/strict');
const M=require('../www/depth-model.js');
const player=(id,entryYear,entryClass=1,status='Signed',offerPackage=0)=>({id,entryYear,entryClass,status,offerPackage,recruit:id.startsWith('recruit-'),positions:['SS']});
const senior=player('senior',2027,5),returner=player('returner',2027),offered=player('recruit-offer',2028,1,'Offered',5000),committed=player('recruit-commit',2028,1,'Committed',10000),scouted=player('recruit-scout',2028,1,'Recruiting',50000);
const players=[senior,returner,offered,committed,scouted];
const funding={budgets:{2027:100000},awards:{senior:{2027:65000},returner:{2027:20000}}};
assert.deepEqual(M.budgetSummary(funding,players,2027),{budget:100000,used:85000,remaining:15000,percent:85,incoming:0});
assert.deepEqual(M.budgetSummary(funding,players,2028),{budget:100000,used:35000,remaining:65000,percent:35,incoming:15000});
assert.equal(M.allocation(funding,returner,2031),20000);
assert.equal(M.allocation(funding,returner,2032),0);
assert.equal(M.budgetSummary(funding,[...players,returner],2028).used,35000);
funding.awards.returner[2029]=0;
assert.equal(M.allocation(funding,returner,2029),0);
assert.equal(M.allocation(funding,returner,2028),20000);
funding.budgets[2029]=120000;
assert.equal(M.budgetSummary(funding,players,2030).budget,120000);
assert.equal(M.budgetSummary(funding,players,2028).budget,100000);
assert.equal(M.budgetSummary({budgets:{2027:0},awards:funding.awards},players,2027).remaining,-85000);
assert.equal(M.budgetSummary({},players,2027).budget,null);
assert.equal(M.budgetSummary({},players,2027).percent,null);
assert.equal(M.compactMoney(65000),'$65k');assert.equal(M.compactMoney(5000),'$5k');assert.equal(M.compactMoney(12500),'$12.5k');assert.equal(M.compactMoney(0),'$0');
const restored=JSON.parse(JSON.stringify(funding));
assert.equal(M.budgetSummary(restored,players,2028).remaining,65000);
console.log('Annual carry-forward, expiration, incoming offers, duplicate prevention, zero overrides, budgets, and formatting passed.');
